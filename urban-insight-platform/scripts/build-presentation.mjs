import { build, transform } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), ".."),
  check = process.argv.includes("--check");
// Packaging only: no dotenv loading, source rewriting, data fetching, or provider changes.
const js = await build({
  absWorkingDir: root,
  entryPoints: ["js/main.js"],
  outfile: "js/atlas.js",
  bundle: true,
  format: "esm",
  target: "es2022",
  minify: true,
  write: false,
  legalComments: "inline",
  banner: {
    js: "/* Generated by npm run build:presentation; edit the source modules, not this file. */",
  },
});
const cssInputs = await Promise.all(
  [
    "css/styles.css",
    "vendor/leaflet/leaflet.css",
    "vendor/gesture/leaflet-gesture-handling.min.css",
  ].map((p) => readFile(resolve(root, p), "utf8")),
);
cssInputs[1] = cssInputs[1].replaceAll(
  "url(images/",
  "url(../vendor/leaflet/images/",
);
const css = await transform(cssInputs.join("\n"), {
  loader: "css",
  minify: true,
  legalComments: "inline",
});
for (const [path, bytes] of [
  ["js/atlas.js", js.outputFiles[0].contents],
  [
    "css/atlas.css",
    Buffer.from(
      "/* Generated by npm run build:presentation; edit styles.css and vendor sources. */\n" +
        css.code,
    ),
  ],
]) {
  if (check) {
    let actual;
    try {
      actual = await readFile(resolve(root, path));
    } catch {
      throw new Error(
        "Missing presentation bundle; run npm run build:presentation",
      );
    }
    if (!Buffer.from(bytes).equals(actual))
      throw new Error(
        "Stale presentation bundle: " +
          path +
          ". Run npm run build:presentation.",
      );
  } else await writeFile(resolve(root, path), bytes);
  console.log(`${check ? "Verified" : "Built"} ${path}: ${bytes.length} bytes`);
}
